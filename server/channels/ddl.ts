/**
 * The DDL for the outreach channel tables (shared/schema.ts: whatsappConnections, whatsappContacts, channelMessages).
 * One list, run by script/migrate-channels.ts and by the real-Postgres tests, so what the tests check is what runs.
 * PURELY ADDITIVE and idempotent: three new tables and their indexes; no existing table changes.
 */
export const CHANNEL_TABLES = ["whatsapp_connections", "whatsapp_contacts", "channel_messages"] as const;

export const CHANNEL_DDL: readonly string[] = [
  `CREATE TABLE IF NOT EXISTS whatsapp_connections (
    id serial PRIMARY KEY,
    organization_id varchar NOT NULL,
    status varchar(16) NOT NULL,
    phone_number_id varchar(40) NOT NULL,
    waba_id varchar(40) NOT NULL,
    display_phone varchar(32),
    verified_name varchar(120),
    access_token_enc text,
    token_key_version smallint,
    last_error_code varchar(40),
    last_error_at timestamp,
    connected_by varchar NOT NULL,
    connected_at timestamp NOT NULL,
    disconnected_at timestamp,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    CONSTRAINT whatsapp_connections_status_ck CHECK (status IN ('active', 'needs_attention', 'disconnected')),
    CONSTRAINT whatsapp_connections_token_ck CHECK ((status = 'disconnected') = (access_token_enc IS NULL) AND (access_token_enc IS NULL) = (token_key_version IS NULL))
  )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS whatsapp_connections_live_org_uq ON whatsapp_connections (organization_id) WHERE status <> 'disconnected'`,
  `CREATE UNIQUE INDEX IF NOT EXISTS whatsapp_connections_live_phone_uq ON whatsapp_connections (phone_number_id) WHERE status <> 'disconnected'`,
  `CREATE TABLE IF NOT EXISTS whatsapp_contacts (
    id serial PRIMARY KEY,
    organization_id varchar NOT NULL,
    phone varchar(20) NOT NULL,
    lead_id integer,
    opted_in_at timestamp,
    opt_in_source varchar(200),
    opt_in_recorded_by varchar,
    opted_out_at timestamp,
    last_inbound_at timestamp,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL
  )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS whatsapp_contacts_org_phone_uq ON whatsapp_contacts (organization_id, phone)`,
  `CREATE INDEX IF NOT EXISTS whatsapp_contacts_lead_idx ON whatsapp_contacts (organization_id, lead_id)`,
  `CREATE TABLE IF NOT EXISTS channel_messages (
    id serial PRIMARY KEY,
    organization_id varchar NOT NULL,
    lead_id integer NOT NULL,
    channel varchar(10) NOT NULL,
    kind varchar(16) NOT NULL,
    direction varchar(3) NOT NULL DEFAULT 'out',
    body text,
    body_hash varchar(64),
    to_address varchar(254),
    template_name varchar(120),
    template_lang varchar(15),
    template_params jsonb,
    status varchar(12) NOT NULL,
    sent_via varchar(6),
    delivery varchar(10),
    provider_message_id varchar(200),
    error_code varchar(40),
    attempts integer NOT NULL DEFAULT 0,
    prompt_version varchar(20),
    claim_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
    edited boolean NOT NULL DEFAULT false,
    created_by varchar(8) NOT NULL DEFAULT 'user',
    created_by_user varchar,
    approved_by varchar,
    approved_at timestamp,
    sent_at timestamp,
    delivered_at timestamp,
    read_at timestamp,
    replied_at timestamp,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    CONSTRAINT channel_messages_status_ck CHECK (status IN ('draft', 'approved', 'sending', 'sent', 'failed', 'uncertain', 'cancelled', 'received')),
    CONSTRAINT channel_messages_channel_ck CHECK (channel IN ('whatsapp', 'linkedin', 'x')),
    CONSTRAINT channel_messages_sent_ck CHECK (status <> 'sent' OR (sent_at IS NOT NULL AND sent_via IS NOT NULL)),
    CONSTRAINT channel_messages_api_ck CHECK (sent_via IS DISTINCT FROM 'api' OR channel = 'whatsapp')
  )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS channel_messages_one_unsent_uq ON channel_messages (lead_id, channel) WHERE direction = 'out' AND status IN ('draft', 'approved', 'sending', 'uncertain')`,
  `CREATE UNIQUE INDEX IF NOT EXISTS channel_messages_provider_uq ON channel_messages (channel, provider_message_id) WHERE provider_message_id IS NOT NULL`,
  `CREATE INDEX IF NOT EXISTS channel_messages_lead_idx ON channel_messages (organization_id, lead_id, created_at)`,
  `CREATE INDEX IF NOT EXISTS channel_messages_sent_idx ON channel_messages (organization_id, channel, sent_at) WHERE sent_via = 'api'`,
];
